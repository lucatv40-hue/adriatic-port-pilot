import { calculateChannelRoute } from "/tmp/cross-project/laguna-nav-pro-f9ea529c559f4b5c9fe39e878f8378bc/src/lib/channels.core.ts";
import { INLETS } from "/tmp/cross-project/laguna-nav-pro-f9ea529c559f4b5c9fe39e878f8378bc/src/lib/inlets.ts";
import { PORTS } from "/dev-server/src/lib/ports.ts";
import { LAGOONS, inside } from "/dev-server/src/lib/sea-route.ts";
const keys = ["lido", "malamocco", "chioggia"];
const d = (a: number[], b: number[]) => Math.hypot(a[0]! - b[0]!, (a[1]! - b[1]!) * 0.7);
function clean(pts: number[][], outer: number[]) {
  let a = pts.filter((q, i) => i === 0 || d(q, pts[i - 1]!) > 2e-5);
  const k = a.findIndex((q) => d(q, outer) < 1e-4); if (k > 0) a = a.slice(0, k + 1);
  // remove spikes (sharp reversals)
  for (let changed = true; changed;) {
    changed = false;
    for (let i = 1; i < a.length - 1; i++) {
      const p = a[i - 1]!, q = a[i]!, r = a[i + 1]!;
      const v1 = [q[0]! - p[0]!, (q[1]! - p[1]!) * 0.7], v2 = [r[0]! - q[0]!, (r[1]! - q[1]!) * 0.7];
      const cos = (v1[0]! * v2[0]! + v1[1]! * v2[1]!) / (Math.hypot(...v1) * Math.hypot(...v2));
      if (cos < -0.5) { a.splice(i, 1); changed = true; break; }
    }
  }
  return a;
}
const out: Record<string, Record<string, number[][]>> = {};
for (const p of PORTS) {
  if (!inside(p, LAGOONS[0]!.area)) continue;
  const key = `${p.lat.toFixed(4)},${p.lon.toFixed(4)}`; out[key] = {};
  for (let i = 0; i < INLETS.length; i++) {
    const inl = INLETS[i]!;
    const r = await calculateChannelRoute({ start: { lat: p.lat, lng: p.lon }, end: inl.outer, speedKnots: 6, hasMast: true, draft: 2 }, true);
    const pts = r.route.points.map((q) => [+q.lat.toFixed(5), +q.lng.toFixed(5)]);
    if (pts.length < 2) { console.error("no route", p.id, inl.name, r.warning); continue; }
    out[key]![keys[i]!] = clean(pts, [inl.outer.lat, inl.outer.lng]);
    console.error(p.id, keys[i], pts.length, "->", out[key]![keys[i]!]!.length);
  }
}
